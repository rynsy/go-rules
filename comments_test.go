package rules

import (
	"slices"
	"strings"
	"testing"
)

func TestRules(t *testing.T) {
	findings, err := CheckSource("x.go", []byte("package x\n\n// why\nvar V = 1 //nolint:forbidigo // why\n\nfunc F() {\n\t// why\n}\n"))
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, f := range findings {
		got = append(got, f.Rule)
	}
	if !slices.Equal(got, []string{"RYG002", "RYG001"}) {
		t.Errorf("rules %v", got)
	}
}

func lines(t *testing.T, path, src string) []int {
	t.Helper()
	findings, err := CheckSource(path, []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	var got []int
	for _, f := range findings {
		got = append(got, f.Line)
	}
	return got
}

func TestComments(t *testing.T) {
	cases := map[string]struct {
		src  string
		want []int
	}{
		"doc comments everywhere a declaration takes one": {`// Package x does x.
package x

// T is a type.
type T struct {
	// A is a field.
	A int
}

// I is an interface.
type I interface {
	// M is a method.
	M()
}

// V is a var.
var V = 1

const (
	// C is a const.
	C = 1
)

// F is a func.
func F() {}
`, nil},
		"comment in a body":            {"package x\n\nfunc F() {\n\t// why\n\t_ = 1\n}\n", []int{4}},
		"trailing comment":             {"package x\n\nvar V = 1 // why\n", []int{3}},
		"trailing comment on a field":  {"package x\n\ntype T struct {\n\tA int // why\n}\n", []int{4}},
		"doc on a local declaration":   {"package x\n\nfunc F() {\n\t// why\n\tvar v int\n\t_ = v\n}\n", []int{4}},
		"block comment":                {"package x\n\nfunc F() {\n\t/* why */\n}\n", []int{4}},
		"floating comment":             {"package x\n\n// floating\n\nvar V = 1\n", []int{3}},
		"license header above package": {"// Copyright x\n\npackage x\n", []int{1}},
		"todo with an issue":           {"package x\n\nfunc F() {\n\t// TODO(#12) cache it\n}\n", nil},
		"todo without an issue":        {"package x\n\nfunc F() {\n\t// TODO cache it\n}\n", []int{4}},
		"todo with issue zero":         {"package x\n\nfunc F() {\n\t// TODO(#0) cache it\n}\n", []int{4}},
		"ponytail and two continuations": {
			"package x\n\nfunc F() {\n\t// ponytail: O(n^2)\n\t// fine below 1k\n\t// then index it\n\t// one too many\n}\n",
			[]int{7},
		},
		"ponytail trailing":              {"package x\n\nvar V = 1 // ponytail: fixed\n", nil},
		"directives":                     {"package x\n\n//go:generate echo\n\nfunc F() {\n\t//go:noinline\n\t_ = 1\n}\n", nil},
		"build constraint":               {"//go:build linux\n\npackage x\n", nil},
		"nolint is linted by nolintlint": {"package x\n\nvar V = 1 //nolint:gosec // G1: why\n", nil},
		"lint:ignore is a comment":       {"package x\n\nvar V = 1 //lint:ignore SA1 why\n", []int{3}},
		"example output": {
			"package x\n\nimport \"fmt\"\n\nfunc ExampleF() {\n\tfmt.Println(1)\n\t// Output:\n\t// 1\n}\n",
			nil,
		},
		"example method in a test file": {
			"package x\n\ntype T struct{}\n\nfunc (T) ExampleF() {\n\t// Output:\n\t// 1\n}\n",
			[]int{6, 7},
		},
		"Example in a production file": {
			"package x\n\nfunc ExampleF() {\n\t// Output:\n\t// 1\n}\n",
			[]int{4, 5},
		},
		"output outside an example":          {"package x\n\nfunc F() {\n\t// Output:\n\t// 1\n}\n", []int{4, 5}},
		"a generated header exempts nothing": {"// Code generated by x. DO NOT EDIT.\n\npackage x\n\nfunc F() {\n\t// prose\n}\n", []int{1, 6}},
		"block comment with a todo":          {"package x\n\nfunc F() {\n\t/* TODO(#1) and any amount of prose */\n}\n", []int{4}},
		"directive-looking prose": {
			"package x\n\nfunc F() {\n\t//nolintbecause reasons\n\t//go:prose here\n\t//line prose\n\t//export two words\n}\n",
			[]int{4, 5, 6, 7},
		},
		"real directives inside a body":         {"package x\n\nfunc F() {\n\t//line x.go:10\n\t_ = 1\n}\n", nil},
		"nolint with a reason":                  {"package x\n\nvar V = 1 //nolint:gosec,revive // G1: why\n", nil},
		"nolint for forbidigo is RYG002":        {"package x\n\nvar V = 1 //nolint:gosec,forbidigo // why\n", []int{3}},
		"nolint for forbidigo as a doc comment": {"package x\n\n//nolint:forbidigo //the clock\nvar V = 1\n", []int{3}},
	}
	for name, c := range cases {
		t.Run(name, func(t *testing.T) {
			path := "x.go"
			if strings.HasPrefix(name, "example") {
				path = "x_test.go"
			}
			got := lines(t, path, c.src)
			if !slices.Equal(got, c.want) {
				t.Errorf("lines %v, want %v", got, c.want)
			}
		})
	}
}

